#!/usr/bin/env node
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontmatter } from './lib/frontmatter.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const AGENTS_DIR = join(ROOT, 'agents');
const CODEX_DIR = join(ROOT, '.codex', 'agents', 'godot-prompter');
const args = new Set(process.argv.slice(2));
const writeMode = args.has('--write');
const checkMode = args.has('--check') || !writeMode;

function encodeTomlMultiline(text) {
  if (text.includes("'''")) {
    throw new Error('Content contains TOML triple single quotes');
  }
  return `'''\n${text.replace(/\s+$/, '')}\n'''`;
}

function renderToml(agentFile, parsed) {
  const { data, body } = parsed;
  if (!data.name) throw new Error(`${agentFile}: frontmatter missing name`);
  if (!data.description) throw new Error(`${agentFile}: frontmatter missing description`);
  const lines = [
    '# This file is generated by scripts/sync-codex-agents.mjs.',
    `# Source: agents/${agentFile}`,
    '# Edit the Markdown source, then run: node scripts/sync-codex-agents.mjs --write',
    '',
    `name = ${JSON.stringify(data.name)}`,
    `description = ${encodeTomlMultiline(data.description)}`,
    `developer_instructions = ${encodeTomlMultiline(body.trimEnd())}`,
  ];
  if (data.model) lines.push(`# model = ${JSON.stringify(data.model)}`);
  return `${lines.join('\n')}\n`;
}

const expected = new Map();
for (const agentFile of readdirSync(AGENTS_DIR).filter(name => name.endsWith('.md')).sort()) {
  const sourcePath = join(AGENTS_DIR, agentFile);
  const parsed = parseFrontmatter(readFileSync(sourcePath, 'utf8'));
  expected.set(agentFile.replace(/\.md$/, '.toml'), renderToml(agentFile, parsed));
}

let hasMismatch = false;
mkdirSync(CODEX_DIR, { recursive: true });

for (const [targetFile, rendered] of expected) {
  const targetPath = join(CODEX_DIR, targetFile);
  const current = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : null;
  if (current !== rendered) {
    hasMismatch = true;
    if (writeMode) {
      writeFileSync(targetPath, rendered);
      console.log(`${current === null ? 'created' : 'updated'} ${targetPath}`);
    } else {
      console.error(`out of sync: ${targetPath}`);
    }
  }
}

for (const name of readdirSync(CODEX_DIR)) {
  const targetPath = join(CODEX_DIR, name);
  if (!statSync(targetPath).isFile() || !name.endsWith('.toml')) continue;
  if (!expected.has(name)) {
    hasMismatch = true;
    if (writeMode) {
      rmSync(targetPath);
      console.log(`removed ${targetPath}`);
    } else {
      console.error(`unexpected mirror: ${targetPath}`);
    }
  }
}

if (checkMode && hasMismatch) process.exit(1);
if (!hasMismatch && checkMode) console.log('Codex agent mirrors are in sync.');
